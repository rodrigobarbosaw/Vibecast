begin;
create schema if not exists playdahora;
revoke all on schema playdahora from public, anon, authenticated;

create table if not exists playdahora.users (
  id text primary key,
  email text not null unique,
  salt text not null,
  password text not null,
  m3u text not null,
  epg text not null default '',
  trial_end bigint not null,
  customer text,
  checkout text,
  source_name text not null default '',
  source_mode text not null default 'm3u' check (source_mode in ('m3u','xtream'))
);
create table if not exists playdahora.sessions (
  token text primary key,
  user_id text not null references playdahora.users(id) on delete cascade,
  expires bigint not null
);
create table if not exists playdahora.playback (
  user_id text not null references playdahora.users(id) on delete cascade,
  media_key text not null,
  position double precision not null check (position >= 0),
  duration double precision not null check (duration > 0),
  updated bigint not null,
  episode text,
  primary key (user_id, media_key)
);
create table if not exists playdahora.channel_views (
  channel text primary key,
  views bigint not null check (views >= 0)
);
create table if not exists playdahora.channel_history (
  user_id text not null references playdahora.users(id) on delete cascade,
  channel text not null,
  watched bigint not null,
  primary key (user_id, channel)
);
create table if not exists playdahora.channel_favorites (
  user_id text not null references playdahora.users(id) on delete cascade,
  channel text not null,
  rowid bigint generated by default as identity unique,
  primary key (user_id, channel)
);

create index if not exists sessions_expiry on playdahora.sessions(expires);
create index if not exists sessions_user on playdahora.sessions(user_id);
create index if not exists playback_recent on playdahora.playback(user_id, updated desc);
create index if not exists channel_history_recent on playdahora.channel_history(user_id, watched desc);
create index if not exists channel_favorites_order on playdahora.channel_favorites(user_id, rowid desc);
create index if not exists channel_views_rank on playdahora.channel_views(views desc, channel);

revoke all on all tables in schema playdahora from public, anon, authenticated;
revoke all on all sequences in schema playdahora from public, anon, authenticated;
alter table playdahora.users enable row level security;
alter table playdahora.sessions enable row level security;
alter table playdahora.playback enable row level security;
alter table playdahora.channel_views enable row level security;
alter table playdahora.channel_history enable row level security;
alter table playdahora.channel_favorites enable row level security;
commit;
